# shellcheck shell=sh disable=SC3043
# SC3043: `local` is not POSIX, but busybox ash (the hashicorp/vault image), dash and bash all have it.
# Pure functions that turn secrets.manifest into Vault policies and Vault Agent configuration.
# Sourced by init.sh and start-agent.sh. Nothing here talks to Vault or prints a secret value.

VAULT_MANIFEST="${VAULT_MANIFEST:-/vault/manifest/secrets.manifest}"
# The KV v2 mount every path below lives under.
VAULT_KV_MOUNT="${VAULT_KV_MOUNT:-secret}"

vl_die() {
  printf 'vault-lib: %s\n' "$*" >&2
  return 1
}

# The manifest without comments and blank lines, one "entry NAME" per line.
vl_entries() {
  [ -r "$VAULT_MANIFEST" ] || {
    vl_die "cannot read manifest $VAULT_MANIFEST"
    return 1
  }
  sed -e 's/#.*//' -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' "$VAULT_MANIFEST" |
    awk 'NF { print $1, $2, NF }' |
    while read -r entry name fields; do
      if [ "$fields" != 2 ]; then
        vl_die "manifest line for $entry $name has $fields fields, expected 2"
        return 1
      fi
      printf '%s %s\n' "$entry" "$name"
    done
}

# Every application: each entry other than `shared`, once.
vl_apps() {
  vl_entries | awk '$1 != "shared" && !seen[$1]++ { print $1 }'
}

# Rejects anything that would break a policy path, a template or a file name: entries are
# lower-case path segments, names are identifiers (they become file names, and field accesses in
# the agent's templates, so that error_on_missing_key catches a key missing from Vault).
vl_validate() {
  local entries
  entries="$(vl_entries)" || return 1
  [ -n "$entries" ] || {
    vl_die "manifest $VAULT_MANIFEST lists no secrets"
    return 1
  }
  printf '%s\n' "$entries" | {
    seen=' '
    while read -r entry name; do
      printf '%s' "$entry" | grep -Eq '^[a-z][a-z0-9-]*$' || {
        vl_die "entry '$entry' must match [a-z][a-z0-9-]*"
        return 1
      }
      printf '%s' "$name" | grep -Eq '^[A-Za-z_][A-Za-z0-9_]*$' || {
        vl_die "name '$name' must match [A-Za-z_][A-Za-z0-9_]*"
        return 1
      }
      case "$seen" in
        *" $entry/$name "*)
          vl_die "name $name is listed twice under $entry"
          return 1
          ;;
      esac
      seen="$seen$entry/$name "
    done
  }
}

# "entry NAME" for every secret APP reads: the shared ones and its own.
vl_app_secrets() {
  vl_entries | awk -v app="$1" '$1 == "shared" || $1 == app'
}

# The file names Vault Agent renders for APP; the agent's healthcheck waits for all of them.
vl_expected() {
  vl_app_secrets "$1" | awk '{ print $2 }'
}

# Read-only access to the shared entry and APP's own. Fixed paths, no list and no wildcard: an
# application cannot discover which other entries exist.
# https://developer.hashicorp.com/vault/docs/concepts/policies
vl_policy() {
  local app="$1" entry
  printf '# Generated from secrets.manifest by vault-lib.sh for %s.\n' "$app"
  for entry in shared "$app"; do
    printf 'path "%s/data/%s" {\n  capabilities = ["read"]\n}\n' "$VAULT_KV_MOUNT" "$entry"
  done
}

# What the delivery step (init.sh deliver) may do with its long-lived token: read each
# application's role_id and mint a secret_id for it, only response-wrapped and briefly.
# min_wrapping_ttl = "1s" makes response wrapping mandatory for the path.
# https://developer.hashicorp.com/vault/docs/concepts/policies#parameter-constraints
vl_issuer_policy() {
  local app
  printf '# Generated by vault-lib.sh: delivers wrapped secret_ids to Vault Agent.\n'
  for app in $(vl_apps); do
    printf 'path "auth/approle/role/%s/role-id" {\n  capabilities = ["read"]\n}\n' "$app"
    printf 'path "auth/approle/role/%s/secret-id" {\n  capabilities = ["update"]\n  min_wrapping_ttl = "1s"\n  max_wrapping_ttl = "10m"\n}\n' "$app"
  done
}

# Day-to-day secret maintenance without root: KV entries and their versions, nothing else.
# patch is a capability of its own, used by `vault kv patch`.
# https://developer.hashicorp.com/vault/docs/commands/kv/patch
vl_admin_policy() {
  printf '# Generated by vault-lib.sh: secret maintenance.\n'
  printf 'path "%s/data/*" {\n  capabilities = ["create", "read", "update", "patch", "delete"]\n}\n' "$VAULT_KV_MOUNT"
  printf 'path "%s/metadata/*" {\n  capabilities = ["read", "list", "delete"]\n}\n' "$VAULT_KV_MOUNT"
  printf 'path "%s/undelete/*" {\n  capabilities = ["update"]\n}\n' "$VAULT_KV_MOUNT"
  printf 'path "%s/destroy/*" {\n  capabilities = ["update"]\n}\n' "$VAULT_KV_MOUNT"
}

# Vault Agent configuration for APP: AppRole auto-auth with a response-wrapped secret_id, and one
# template per secret rendering the bare value to SECRETS_DIR/NAME, readable by the agent's uid only.
#   https://developer.hashicorp.com/vault/docs/agent-and-proxy/autoauth/methods/approle
#   https://developer.hashicorp.com/vault/docs/agent-and-proxy/agent/template
vl_agent_config() {
  local app="$1" secrets_dir="$2" approle_dir="$3" addr="$4" ca_cert="$5"
  vl_validate || return 1
  cat <<HCL
# Generated by vault-lib.sh for $app.
pid_file = "/tmp/vault-agent.pid"

vault {
  address = "$addr"
  ca_cert = "$ca_cert"
}

auto_auth {
  method "approle" {
    mount_path = "auth/approle"
    config = {
      role_id_file_path                   = "$approle_dir/role-id"
      secret_id_file_path                 = "$approle_dir/secret-id"
      remove_secret_id_file_after_reading = true
      secret_id_response_wrapping_path    = "auth/approle/role/$app/secret-id"
    }
  }
}

template_config {
  # KV v2 has no lease; re-read this often so a rotated value reaches the file within a minute.
  static_secret_render_interval = "1m"
}
HCL
  vl_app_secrets "$app" | while read -r entry name; do
    cat <<HCL

template {
  destination          = "$secrets_dir/$name"
  perms                = "0400"
  error_on_missing_key = true
  contents             = "{{ with secret \"$VAULT_KV_MOUNT/data/$entry\" }}{{ .Data.data.$name }}{{ end }}"
}
HCL
  done
}
